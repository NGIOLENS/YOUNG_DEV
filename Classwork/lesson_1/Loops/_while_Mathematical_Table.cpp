#include<iostream>
using namespace std;
int main()
{
	int i = 1;
	int j = 1;

	while(i <= 10)
	{
		while( j <= 15)
		{
			cout<<"\n"<<i<<" * "<<j<<" = "<<(i * j);
			j++;
		}
		j = 1;		
		cout<<"\n-----------------------------------------------------------------------------------------------------------------------------------------------------------";
		i++;
	}

	cout<<"\n\n";
	return 0;
}
