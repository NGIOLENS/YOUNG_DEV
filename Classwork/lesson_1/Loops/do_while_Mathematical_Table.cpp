#include<iostream>
using namespace std;
int main()
{
	int i = 1;
	int j = 1;

	do
	{
		j = 1;
		do
		{
			cout<<"\n"<<i<<" * "<<j<<" = "<<(i * j);
			j++;
		}while( j <= 15);
				
		cout<<"\n-----------------------------------------------------------------------------------------------------------------------------------------------------------";
		i++;
	}while(i <= 10);

	cout<<"\n\n";
	return 0;
}
